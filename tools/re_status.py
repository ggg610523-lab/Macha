#!/usr/bin/env python3
"""Report reverse-engineering coverage over every shipped binary.

Reads the package inventory and the decompiler output, cross-references them,
and writes re/STATUS.md plus re/missing.txt. No third-party modules.
"""
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG_ROOT = os.path.abspath(os.path.join(HERE, "..", "pulsar-appexec"))
PKG = os.path.join(PKG_ROOT, "usr", "lib", "pulsar-appexec")


def read_rows(path):
    rows = []
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            header = f.readline().rstrip("\n").split("\t")
            for line in f:
                parts = line.rstrip("\n").split("\t")
                if len(parts) >= 2:
                    rows.append((header, parts))
    except FileNotFoundError:
        pass
    return rows


def done_info(obj_dir):
    marker = os.path.join(obj_dir, "_DONE")
    try:
        with open(marker, encoding="utf-8", errors="replace") as f:
            return f.read().strip()
    except FileNotFoundError:
        pass
    funcs = os.path.join(obj_dir, "functions")
    if os.path.isdir(funcs):
        n = sum(1 for e in os.scandir(funcs)
                if e.is_file() and e.name.endswith(".c") and e.stat().st_size)
        if n:
            return "PARTIAL files=%d (no _DONE)" % n
    return ""


def macho_rows():
    index = read_rows(os.path.join(HERE, "src", "macho", "index.tsv"))
    out = []
    for header, parts in index:
        rel = parts[0]
        row = dict(zip(header, parts))
        slug = rel.replace("/", "_")
        status = done_info(os.path.join(HERE, "src", "macho", slug))
        out.append({"rel": rel, "slug": slug, "bytes": int(row.get("bytes") or 0),
                    "exports": int(row.get("exports") or 0),
                    "imports": int(row.get("imports") or 0),
                    "status": status})
    return out


def elf_rows():
    """Enumerate every ELF object in the package, including ones never listed."""
    summary = {}
    for _header, parts in read_rows(os.path.join(HERE, "src", "elf", "_SUMMARY.tsv")):
        stats = parts[1] if len(parts) > 1 else "-"
        status = parts[-1] if len(parts) > 2 else "-"
        summary[parts[0]] = (stats, status)
    rows = []
    for root, _dirs, files in os.walk(PKG_ROOT):
        for name in files:
            path = os.path.join(root, name)
            try:
                with open(path, "rb") as f:
                    if f.read(4) != b"\x7fELF":
                        continue
            except OSError:
                continue
            rel = os.path.relpath(path, PKG_ROOT)
            stats, status = summary.get(rel, ("-", "-"))
            info = done_info(os.path.join(HERE, "src", "elf", rel.replace("/", "_")))
            if info.startswith("functions="):
                stats, status = info, "DONE"
            elif info.startswith("PARTIAL"):
                status = info
            elif status == "-":
                status = "not started"
            rows.append({"rel": rel, "stats": stats, "status": status})
    return sorted(rows, key=lambda r: r["rel"])


def closure_set():
    path = os.path.join(HERE, "logs", "macho", "closure.txt")
    names = set()
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                names.add(os.path.basename(line))
    except FileNotFoundError:
        pass
    return names


def main():
    macho = macho_rows()
    elf = elf_rows()
    closure = closure_set()

    done = [m for m in macho if m["status"].startswith("functions=")]
    partial = [m for m in macho if m["status"].startswith("PARTIAL")]
    pending = [m for m in macho if not m["status"]]
    closure_done = [m for m in done if os.path.basename(m["rel"]) in closure]

    re_dir = os.path.join(HERE, "re")
    os.makedirs(re_dir, exist_ok=True)
    with open(os.path.join(re_dir, "missing.txt"), "w", encoding="utf-8") as f:
        for m in pending + partial:
            f.write(m["rel"] + "\n")

    lines = ["# Reverse-engineering coverage", "",
             "Generated by `tools/re_status.py` from `src/macho/index.tsv`,",
             "`src/elf/_SUMMARY.tsv`, and the `_DONE` markers.", "",
             "## Mach-O", "",
             "| Objects | Count |", "|---|---:|",
             "| Shipped | %d |" % len(macho),
             "| Decompiled (`_DONE`) | %d |" % len(done),
             "| Interrupted (files, no `_DONE`) | %d |" % len(partial),
             "| Not started | %d |" % len(pending),
             "| CotEditor live closure decompiled | %d/%d |" %
             (len(closure_done), len(closure)),
             "",
             "## Remaining Mach-O, largest first", "",
             "| Bytes | Exports | Imports | Object | State |", "|---:|---:|---:|---|---|"]
    for m in sorted(pending + partial, key=lambda r: -r["bytes"]):
        lines.append("| %d | %d | %d | `%s` | %s |" %
                     (m["bytes"], m["exports"], m["imports"], m["rel"],
                      m["status"] or "not started"))

    lines += ["", "## ELF", "", "| Object | Stats | Status |", "|---|---|---|"]
    for r in elf:
        lines.append("| `%s` | %s | %s |" % (r["rel"], r["stats"], r["status"]))

    with open(os.path.join(re_dir, "STATUS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    print("macho: %d shipped, %d done, %d interrupted, %d not started"
          % (len(macho), len(done), len(partial), len(pending)))
    print("elf:   %d rows, %d done"
          % (len(elf), sum(1 for r in elf if r["status"] == "DONE")))
    print("closure: %d/%d decompiled" % (len(closure_done), len(closure)))
    print("wrote", os.path.join(re_dir, "STATUS.md"))
    print("wrote", os.path.join(re_dir, "missing.txt"))


if __name__ == "__main__":
    sys.exit(main())
